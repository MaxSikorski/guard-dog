#!/usr/bin/env bash
# Rebuild docs/demo/watchdog.wasm.js, the browser demo's engine, from source.
#
# The engine is the real Judge C checker and the safe text renderer plus the
# demo scenes (crates/gd-demo, exported by crates/gd-demo-wasm), built for
# WebAssembly: no network, no Tor, no keys. The page's Content-Security-Policy
# forbids every fetch, so the module ships as base64 in a script file. The
# .wasm itself is not committed: it is written under cargo's target directory,
# and its SHA-256 (of the same bytes the script file carries) is printed here
# and pinned in docs/demo/README.md.
#
# It also prints the SHA-256 of the events JSON the engine produces (also pinned).
#
# Needs Rust from rust-toolchain.toml (the first run adds the wasm target),
# plus jq and strings.
set -euo pipefail
cd "$(dirname "$0")/../.."

rustup target add wasm32-unknown-unknown >/dev/null

# The real target directory (CARGO_TARGET_DIR, a config setting, or ./target).
TARGET_DIR="$(cargo metadata --format-version 1 --no-deps | jq -r .target_directory)"

# Keep local folder names (and so usernames) out of the built file, and make
# the bytes the same for a git or a sparse registry: every crate source path
# under CARGO_HOME becomes /cargo/..., with the registry's index directory name
# (which differs between the two) dropped.
CARGO_HOME_DIR="${CARGO_HOME:-$HOME/.cargo}"
REGISTRY_SRC="$CARGO_HOME_DIR/registry/src"
US="$(printf '\037')"  # cargo splits CARGO_ENCODED_RUSTFLAGS on this, so paths with spaces survive
FLAGS=""
if [ -d "$REGISTRY_SRC" ]; then
    for index in "$REGISTRY_SRC"/*; do
        [ -d "$index" ] && FLAGS="${FLAGS}--remap-path-prefix=$index=/cargo/registry${US}"
    done
fi
export CARGO_ENCODED_RUSTFLAGS="${FLAGS}--remap-path-prefix=$CARGO_HOME_DIR=/cargo${US}--remap-path-prefix=$PWD=guard-dog"

cargo rustc --locked -p gd-demo-wasm --lib --release \
    --target wasm32-unknown-unknown --crate-type cdylib \
    --config 'profile.release.opt-level="s"' \
    --config 'profile.release.lto=true' \
    --config 'profile.release.codegen-units=1' \
    --config 'profile.release.strip=true' \
    --config 'profile.release.panic="abort"'

BUILT="$TARGET_DIR/wasm32-unknown-unknown/release/gd_demo_wasm.wasm"
WASM="$TARGET_DIR/watchdog.wasm"
cp "$BUILT" "$WASM"

# No local path or user name may be in the file. The strings go to a file
# first, so a grep that exits early can't hide a hit behind a closed pipe.
STRINGS="$(mktemp)"
trap 'rm -f "$STRINGS"' EXIT
strings -n 6 "$WASM" > "$STRINGS"
for needle in "$HOME" "/Users/$(whoami)" "/home/$(whoami)" "$PWD"; do
    if grep -F -q -e "$needle" "$STRINGS"; then
        echo "error: the engine still contains a local path: $needle" >&2
        exit 1
    fi
done

# The same bytes as a script file: window.GD_WASM_BASE64 = "...".
{
    printf '/* Generated by docs/demo/build.sh. Do not edit. */\n'
    printf 'window.GD_WASM_BASE64="'
    base64 < "$WASM" | tr -d '\n'
    printf '";\n'
} > docs/demo/watchdog.wasm.js

echo "engine: $(wc -c < "$WASM" | tr -d ' ') bytes (docs/demo/watchdog.wasm.js carries these bytes)"
shasum -a 256 "$WASM" | sed 's|  .*|  watchdog.wasm|'

# The events the engine hands the page, hashed from source (the same bytes the test pins).
env -u CARGO_ENCODED_RUSTFLAGS cargo run --locked -q -p gd-demo --example events_hash
